// Bundles the engine into self-contained Base44 backend functions.
//
// Base44 functions are single Deno files, so the zero-dependency modules in
// src/ are concatenated (imports between them removed, `export` kept only in
// the engine bundle) and each function gets a Deno.serve entry point.
//
//   node scripts/build-base44.mjs          write base44/dist/*
//   node scripts/build-base44.mjs --check  fail if base44/dist is out of date

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SDK_IMPORT = "import { createClientFromRequest } from 'npm:@base44/sdk@0.8.59';";

// Dependency order: each module only imports modules listed before it.
export const MODULES = [
  'src/provenance.js',
  'src/stats.js',
  'src/marketPosition.js',
  'src/analyticsAgent.js',
  'src/render.js',
  'src/pipeline.js',
  'src/connectors/googlePlaces.js',
  'src/connectors/metaGraph.js',
  'src/base44Handlers.js',
];

const FUNCTIONS = {
  generateCompetitivePosition: {
    handler: 'handleGenerateCompetitivePosition',
    doc: 'Builds the competitor market-position table and the analytical report (EN/AR) from stored data and saves them on Report, Benchmark and Competitor. Body: { prospect_id, languages?, use_llm? }',
  },
  refreshMarketData: {
    handler: 'handleRefreshMarketData',
    doc: 'Pulls live numbers from Google Places (prospect + competitors in radius) and Meta Graph (Instagram) and stores them with their sources. Body: { prospect_id, radius_miles?, included_types? }',
  },
};

function stripModule(src, keepExports) {
  // Remove relative imports (single- or multi-line).
  let out = src.replace(/^import\s[\s\S]*?from\s+['"]\.{1,2}\/[^'"]+['"];?\s*$/gm, '');
  if (!keepExports) out = out.replace(/^export\s+(?=(async\s+)?(function|class|const|let)\b)/gm, '');
  return out.trim();
}

function exportedNames(src) {
  const names = [];
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:function|class|const|let)\s+([A-Za-z0-9_$]+)/gm)) names.push(m[1]);
  return names;
}

export function buildEngine() {
  const parts = [];
  const names = [];
  for (const rel of MODULES) {
    const src = readFileSync(join(root, rel), 'utf8');
    names.push(...exportedNames(src));
    parts.push(`// ---- ${rel} ----\n${stripModule(src, false)}`);
  }
  const dupes = names.filter((n, i) => names.indexOf(n) !== i);
  if (dupes.length) throw new Error(`Duplicate top-level names across modules: ${dupes.join(', ')}`);
  return { body: parts.join('\n\n'), names };
}

const HEADER = '// GENERATED by scripts/build-base44.mjs from src/ — do not edit by hand.\n// Run `npm run build:base44` after changing src/.\n';

export function buildOutputs() {
  const { body, names } = buildEngine();
  const outputs = {};
  outputs['base44/dist/engine.bundle.js'] = `${HEADER}\n${body}\n\nexport { ${names.join(', ')} };\n`;
  for (const [name, fn] of Object.entries(FUNCTIONS)) {
    outputs[`base44/dist/functions/${name}.js`] = `${HEADER}// Base44 backend function "${name}".\n// ${fn.doc}\n\n${SDK_IMPORT}\n\n${body}\n\n`
      + `Deno.serve(toRequestHandler(${fn.handler}, createClientFromRequest));\n`;
  }
  return outputs;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const check = process.argv.includes('--check');
  const outputs = buildOutputs();
  let stale = [];
  for (const [rel, content] of Object.entries(outputs)) {
    const abs = join(root, rel);
    if (check) {
      if (!existsSync(abs) || readFileSync(abs, 'utf8') !== content) stale.push(rel);
    } else {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, content);
      console.log(`wrote ${rel} (${content.length} bytes)`);
    }
  }
  if (check && stale.length) {
    console.error(`Out of date: ${stale.join(', ')}. Run npm run build:base44.`);
    process.exit(1);
  }
  if (check) console.log('base44/dist is up to date');
}
